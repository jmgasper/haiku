/* Bluetooth Core Specification LE legacy c1 and s1 sample vectors. */
#include <LELegacyPairingCrypto.h>

#include <stdio.h>
#include <string.h>


static bool
Matches(const uint8_t* actual, const uint8_t* expected)
{
	return memcmp(actual, expected, 16) == 0;
}


int
main()
{
	const uint8_t tk[16] = {};
	const uint8_t random[16] = {
		0xe0,0x2e,0x70,0xc6,0x4e,0x27,0x88,0x63,
		0x0e,0x6f,0xad,0x56,0x21,0xd5,0x83,0x57
	};
	const uint8_t request[7] = {1,1,0,0,0x10,7,7};
	const uint8_t response[7] = {2,3,0,0,8,0,5};
	const uint8_t initiatorAddress[6] = {0xa6,0xa5,0xa4,0xa3,0xa2,0xa1};
	const uint8_t responderAddress[6] = {0xb6,0xb5,0xb4,0xb3,0xb2,0xb1};
	const uint8_t expectedConfirm[16] = {
		0x86,0x3b,0xf1,0xbe,0xc5,0x4d,0xa7,0xd2,
		0xea,0x88,0x89,0x87,0xef,0x3f,0x1e,0x1e
	};
	uint8_t confirm[16];
	bool c1 = Bluetooth::LELegacyConfirm(tk, random, request, response,
		1, initiatorAddress, 0, responderAddress, confirm)
		&& Matches(confirm, expectedConfirm);

	const uint8_t firstRandom[16] = {
		0x88,0x77,0x66,0x55,0x44,0x33,0x22,0x11,
		0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,0x00
	};
	const uint8_t secondRandom[16] = {
		0x00,0xff,0xee,0xdd,0xcc,0xbb,0xaa,0x99,
		0x08,0x07,0x06,0x05,0x04,0x03,0x02,0x01
	};
	const uint8_t expectedKey[16] = {
		0x62,0xa0,0x6d,0x79,0xae,0x16,0x42,0x5b,
		0x9b,0xf4,0xb0,0xe8,0xf0,0xe1,0x1f,0x9a
	};
	uint8_t key[16];
	bool s1 = Bluetooth::LELegacyShortTermKey(tk, firstRandom,
		secondRandom, key) && Matches(key, expectedKey);
	// Bluetooth Core Specification, Vol 3 Part H, Appendix D.7, ah vector.
	const uint8_t irk[16] = {
		0x9b,0x7d,0x39,0x0a,0xa6,0x10,0x10,0x34,
		0x05,0xad,0xc8,0x57,0xa3,0x34,0x02,0xec
	};
	const uint8_t privateAddress[6] = {0xaa,0xfb,0x0d,0x94,0x81,0x70};
	uint8_t wrongAddress[6];
	memcpy(wrongAddress, privateAddress, sizeof(wrongAddress));
	wrongAddress[0] ^= 1;
	bool ah = Bluetooth::LEResolvePrivateAddress(irk, privateAddress)
		&& !Bluetooth::LEResolvePrivateAddress(irk, wrongAddress)
		&& !Bluetooth::LEResolvePrivateAddress(tk, privateAddress);
	printf("le_legacy_c1=%s le_legacy_s1=%s le_ah=%s\n",
		c1 ? "pass" : "fail", s1 ? "pass" : "fail",
		ah ? "pass" : "fail");
	return c1 && s1 && ah ? 0 : 1;
}
