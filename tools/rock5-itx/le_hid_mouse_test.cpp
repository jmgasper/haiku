/* Descriptor-driven LE mouse report decoding. MIT License. */
#include <LEHIDMouseDecoder.h>

#include <stdio.h>


int
main()
{
	const uint8 descriptor[] = {
		0x05,0x01, 0x09,0x02, 0xa1,0x01, 0x09,0x01, 0xa1,0x00,
		0x85,0x01, 0x05,0x09, 0x19,0x01, 0x29,0x03, 0x15,0x00,
		0x25,0x01, 0x95,0x03, 0x75,0x01, 0x81,0x02, 0x95,0x01,
		0x75,0x05, 0x81,0x03, 0x05,0x01, 0x09,0x30, 0x09,0x31,
		0x09,0x38, 0x15,0x81, 0x25,0x7f, 0x75,0x08, 0x95,0x03,
		0x81,0x06, 0xc0,0xc0
	};
	Bluetooth::LEHIDMouseDecoder decoder;
	Bluetooth::LEMouseReport report;
	const uint8 value[] = { 0x05, 0x05, 0xfd, 0x01 };
	bool okay = decoder.Init(descriptor, sizeof(descriptor)) == B_OK
		&& decoder.SupportsReport(1) && !decoder.SupportsReport(2)
		&& decoder.Decode(1, value, sizeof(value), report) == B_OK
		&& report.x == 5 && report.y == -3 && report.wheelY == 1
		&& report.buttons == 5
		&& decoder.Decode(1, value, sizeof(value) - 1, report) == B_BAD_DATA
		&& decoder.Decode(2, value, sizeof(value), report) == B_ENTRY_NOT_FOUND;
	printf("le_hid_mouse_decoder=%s\n", okay ? "pass" : "fail");
	return okay ? 0 : 1;
}
